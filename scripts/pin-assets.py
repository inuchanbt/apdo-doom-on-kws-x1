"""Select frequently missed Freedoom pages for the preserved upper code region."""
from pathlib import Path
import json
from block_codec import encode
ROOT=Path(__file__).resolve().parents[1]
data=(ROOT/'vendor/dmc100-doom/build/packs/E1M1/DOOM.DAT').read_bytes()
frequency=json.loads((ROOT/'artifacts/page-miss-frequency.json').read_text())
pages=[encode(data[at:at+1024].ljust(1024,b'\0')) for at in range(0,len(data),1024)]
budget=120*1024
selected=[]
used=0
for page in sorted(range(len(pages)),key=lambda p:frequency[p]/len(pages[p]),reverse=True):
    if frequency[page] and used+len(pages[page])<=budget:
        selected.append(page)
        used+=len(pages[page])
selected.sort()
blob=bytearray()
entries=[]
for page in selected:
    entries.append((page,len(blob),len(pages[page])))
    blob+=pages[page]
(ROOT/'overlays/firmware/game_pages.bin').write_bytes(blob)
source='''// SPDX-License-Identifier: GPL-2.0-or-later
//! Pinned Freedoom 0.13.0 E1M1 asset pages; generated by pin-assets.py.
#[unsafe(link_section = ".upper.assets")]
static DATA: [u8; %d] = *include_bytes!("game_pages.bin");
const PAGES: &[(u32,u32,u16)] = &[
'''%len(blob)
source+=''.join(f'    ({page},{offset},{size}),\n' for page,offset,size in entries)
source+=''' ];
pub fn get(base:u32) -> Option<&'static [u8]> {
    let page=base/1024;
    let i=PAGES.binary_search_by_key(&page,|entry|entry.0).ok()?;
    let (_,at,len)=PAGES[i];
    Some(&DATA[at as usize..at as usize+len as usize])
}
'''
(ROOT/'overlays/firmware/pinned_assets.rs').write_text(source,encoding='utf-8',newline='\n')
(ROOT/'artifacts/pinned-assets.json').write_text(json.dumps(dict(pages=len(selected),bytes=len(blob),entries=entries),indent=2)+'\n')
print(f'Pinned {len(selected)} pages in {len(blob)} bytes')
